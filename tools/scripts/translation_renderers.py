"""Deterministic native catalogue bytes from a validated shared source."""

from collections.abc import Mapping, Sequence
import json
from pathlib import PurePosixPath
from xml.etree import ElementTree

from translation_sources import Catalogue
from translation_templates import TOKENS, render

ANDROID = PurePosixPath("clients/android/app/src/main/res")
DESKTOP = PurePosixPath("clients/desktop/ui/i18n")
APPLE = PurePosixPath("clients/ios/DYApp/Localizable.xcstrings")
ESCAPES = {
    "\\": "\\\\",
    '"': '\\"',
    "'": "\\'",
    "\n": "\\n",
    "\t": "\\t",
    "\r": "\\u000d",
}


def android_literal(text: str) -> str:
    """AAPT quotes preserve whitespace; escapes preserve literal characters."""
    value = "".join(ESCAPES.get(char, char) for char in text)
    if text.startswith(("@", "?", "#")):
        value = "\\" + value
    return '"' + value + '"'


def android(values: Mapping[str, str]) -> bytes:
    root = ElementTree.Element("resources")
    for key, text in sorted(values.items()):
        ElementTree.SubElement(
            root, "string", name=key
        ).text = android_literal(text)
    ElementTree.indent(root, space="    ")
    header = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/scripts/generate-translations.py. -->\n"
    )
    return (
        header + ElementTree.tostring(root, encoding="unicode") + "\n"
    ).encode("utf-8")


def android_languages(languages: Sequence[str]) -> bytes:
    """Keep the app language picker on the canonical source inventory."""
    root = ElementTree.Element(
        "locale-config",
        {"xmlns:android": "http://schemas.android.com/apk/res/android"},
    )
    for language in sorted(languages):
        ElementTree.SubElement(root, "locale", {"android:name": language})
    ElementTree.indent(root, space="    ")
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/scripts/generate-translations.py. -->\n"
        + ElementTree.tostring(root, encoding="unicode")
        + "\n"
    ).encode("utf-8")


def json_bytes(value: object) -> bytes:
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode(
        "utf-8"
    )


def apple(locales: Mapping[str, Mapping[str, str]], default: str) -> bytes:
    if default not in locales:
        raise ValueError("Apple source language must exist")
    keys = set(locales[default])
    if any(set(values) != keys for values in locales.values()):
        raise ValueError("Apple language inventories differ")
    strings = {
        key: {
            "localizations": {
                tag: {
                    "stringUnit": {
                        "state": "translated",
                        "value": locales[tag][key],
                    }
                }
                for tag in sorted(locales)
            }
        }
        for key in sorted(keys)
    }
    return json_bytes(
        {"sourceLanguage": default, "strings": strings, "version": "1.0"}
    )


def native_values(
    catalogue: Catalogue, platform: str, language: str
) -> dict[str, str]:
    result = {}
    for key, message in sorted(catalogue.messages.items()):
        for target in message.bindings:
            if target.platform != platform:
                continue
            if target.key in result:
                raise ValueError(
                    f"Duplicate rendered native key: {target.key}"
                )
            result[target.key] = render(
                catalogue.texts[language][key],
                message.arguments,
                platform,
                target.tokens,
            )
    if not result:
        raise ValueError(f"No native resources selected for {platform}")
    return result


def plan(
    catalogue: Catalogue, platforms: Sequence[str]
) -> dict[PurePosixPath, bytes]:
    """Render every selected native output in memory, without file IO."""
    if not platforms or set(platforms) - set(TOKENS):
        raise ValueError("Select at least one known catalogue platform")
    result = {}
    if "android" in platforms:
        result[ANDROID / "xml/app_languages.xml"] = android_languages(
            list(catalogue.languages)
        )
    for platform in sorted(set(platforms)):
        locales = {
            tag: native_values(catalogue, platform, tag)
            for tag in sorted(catalogue.languages)
        }
        if platform == "apple":
            result[APPLE] = apple(locales, catalogue.default)
        else:
            for tag, values in locales.items():
                if platform == "android":
                    path = ANDROID / catalogue.languages[tag] / "strings.xml"
                    result[path] = android(values)
                else:
                    result[DESKTOP / f"{tag}.json"] = json_bytes(
                        dict(sorted(values.items()))
                    )
    return result
