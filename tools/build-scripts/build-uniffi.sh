## Usage

### Swift (iOS)

```swift
import DYAppCore

// Initialize app
let message = initializeApp()
print(message)

// Create user profile
let profile = UserProfile(
    userId: "user-123",
    name: "Alice",
    bio: "Software engineer",
    age: 28
)

// Search profiles
let results = searchProfiles(minAge: 25, maxAge: 35)

// Send message
let msg = ChatMessage(
    messageId: "msg-1",
    fromUserId: "user-123",
    toUserId: "user-456",
    content: "Hello!",
    timestamp: Int64(Date().timeIntervalSince1970)
)

do {
    let result = try sendMessage(message: msg)
    print("Message sent: \(result)")
} catch let error as AppError {
    print("Error: \(error)")
}
```

### Kotlin (Android)

```kotlin
import com.dyapp.core.*

// Initialize app
val message = initializeApp()
Log.d("D", message)

// Create user profile
val profile = UserProfile(
    userId = "user-123",
    name = "Alice",
    bio = "Software engineer",
    age = 28
