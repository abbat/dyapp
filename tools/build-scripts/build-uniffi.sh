```

## Build Integration

### Xcode

1. Target → Build Phases
2. New Run Script Phase
3. Add: `./tools/xcode-uniffi-build.sh`

### Android

Add to `android/app/build.gradle`:

```gradle
apply from: '../build-uniffi.gradle'
```

## Available APIs

- `initialize_app()` - Start the app
- `shutdown_app()` - Stop the app
- `get_app_version()` - App version
- `start_sync(peer_id)` - Begin peer sync
- `get_known_peers()` - List known peers
- `search_profiles(min_age, max_age)` - Find matches
- `send_message(message)` - Send chat message

## Error Handling

All FFI functions return `Result<T, AppError>`:

```swift
// Swift
try doSomething()
```

```kotlin
// Kotlin
try {
    doSomething()
} catch (e: AppError) {
    // handle error
}
```

## Troubleshooting

### Bindings not found

Make sure `uniffi` is in Cargo.toml:

```toml
[dependencies]
uniffi = { version = "0.25", features = ["cli"] }
```

### Build fails

Run with verbose output:
```bash
RUST_BACKTRACE=1 ./tools/build-scripts/build-uniffi.sh
```
