#!/bin/bash
# Generate UniFFI bindings for Swift and Kotlin from Rust code

set -euo pipefail

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# Configuration
PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
BUILD_DIR="${PROJECT_ROOT}/target/uniffi"

echo -e "${YELLOW}🔗 Generating UniFFI bindings...${NC}"

# Check prerequisites
check_prerequisites() {
  echo -e "${YELLOW}📋 Checking prerequisites...${NC}"

  if ! command -v cargo &> /dev/null; then
    echo -e "${RED}❌ Cargo not found${NC}"
    exit 1
  fi

  # Check if uniffi is available
  cd "${PROJECT_ROOT}"
  if ! cargo tree | grep -q "uniffi"; then
    echo -e "${YELLOW}⚠️  uniffi not found in Cargo.toml${NC}"
    echo "   Add to Cargo.toml:"
    echo "   [dependencies]"
    echo "   uniffi = { version = \"0.25\", features = [\"cli\"] }"
  fi

  echo -e "${GREEN}✓ Prerequisites OK${NC}"
}

# Generate Swift bindings
generate_swift_bindings() {
  echo -e "${YELLOW}📱 Generating Swift bindings...${NC}"

  local swift_out="${PROJECT_ROOT}/ios/Generated/DYAppCore"
  mkdir -p "$swift_out"

  cd "${PROJECT_ROOT}"

  # Generate Swift module
  cargo run --bin uniffi-bindgen \
    generate src/ffi.rs \
    --language swift \
    --out-dir "$swift_out" || {
      echo -e "${YELLOW}⚠️  UniFFI CLI not available, using build script method${NC}"
      # Alternative: will be generated during Xcode build
      return
    }

  echo -e "${GREEN}✓ Swift bindings generated${NC}"
}

# Generate Kotlin bindings
generate_kotlin_bindings() {
  echo -e "${YELLOW}🤖 Generating Kotlin bindings...${NC}"

  local kotlin_out="${PROJECT_ROOT}/android/app/src/main/kotlin/generated"
  mkdir -p "$kotlin_out"

  cd "${PROJECT_ROOT}"

  # Generate Kotlin module
  cargo run --bin uniffi-bindgen \
    generate src/ffi.rs \
    --language kotlin \
    --out-dir "$kotlin_out" || {
      echo -e "${YELLOW}⚠️  UniFFI CLI not available, using gradle task method${NC}"
      # Alternative: will be generated by Gradle task
      return
    }

  echo -e "${GREEN}✓ Kotlin bindings generated${NC}"
}

# Create Xcode build phase script
create_xcode_script() {
  echo -e "${YELLOW}🔨 Creating Xcode build phase script...${NC}"

  local xcode_script="${PROJECT_ROOT}/tools/xcode-uniffi-build.sh"
  mkdir -p "$(dirname "$xcode_script")"

  cat > "$xcode_script" <<'EOF'
#!/bin/bash
# Xcode build phase script for UniFFI bindings
# Add as a build phase in Xcode: New Run Script Phase

set -euo pipefail

echo "Building UniFFI bindings for iOS..."

# Get target directory from Xcode environment
CONFIGURATION="${CONFIGURATION:-Release}"
PLATFORM_NAME="${PLATFORM_NAME:-iphoneos}"
SWIFT_VERSION="${SWIFT_VERSION:-5}"

# Build iOS framework
cargo build \
  -p dyapp-core \
  --target aarch64-apple-ios \
  --release

echo "UniFFI binding build complete"
EOF

  chmod +x "$xcode_script"
  echo -e "${GREEN}✓ Xcode script created at: $xcode_script${NC}"
}

# Create Gradle integration task
create_gradle_task() {
  echo -e "${YELLOW}🔧 Creating Gradle uniffi task...${NC}"

  local gradle_file="${PROJECT_ROOT}/android/build-uniffi.gradle"

  cat > "$gradle_file" <<'EOF'
// Gradle task for UniFFI Kotlin bindings
// Include in android/app/build.gradle:
// apply from: '../build-uniffi.gradle'

task generateUniFFIBindings {
    doLast {
        println "Generating UniFFI Kotlin bindings..."

        exec {
            executable = 'cargo'
            args = [
                'build',
                '-p', 'dyapp-core',
                '--target', 'aarch64-linux-android',
                '--release'
            ]
        }

        println "UniFFI binding generation complete"
    }
}

preBuild.dependsOn generateUniFFIBindings
EOF

  echo -e "${GREEN}✓ Gradle task created at: $gradle_file${NC}"
}

