  echo -e "${GREEN}✓ Setup guide created${NC}"
}

# Verify generated files
verify_bindings() {
  echo -e "${YELLOW}🔍 Verifying bindings...${NC}"

  local errors=0

  # Note: Actual verification happens after Xcode/Gradle builds
  echo "  ℹ️  Full verification happens during platform builds"
  echo "  ℹ️  Swift: Check Xcode build output"
  echo "  ℹ️  Kotlin: Check Gradle build output"

  echo -e "${GREEN}✓ Verification OK${NC}"
}

# Main flow
main() {
  echo "Project root: $PROJECT_ROOT"
  echo "Build directory: $BUILD_DIR"
  echo ""

  check_prerequisites
  echo ""

  generate_swift_bindings
  echo ""

  generate_kotlin_bindings
  echo ""

  create_xcode_script
  create_gradle_task
  echo ""

  create_setup_guide
  echo ""

  verify_bindings
  echo ""

  echo -e "${GREEN}✅ UniFFI binding setup complete!${NC}"
  echo ""
  echo "Next steps:"
  echo "  1. Add to Cargo.toml: uniffi = { version = \"0.25\", features = [\"cli\"] }"
  echo "  2. Run: cargo build (generates bindings)"
  echo "  3. Xcode: Add build phase script"
  echo "  4. Gradle: Add: apply from: '../build-uniffi.gradle'"
  echo ""
  echo "See UNIFFI_SETUP.md for detailed usage"
}

main "$@"
